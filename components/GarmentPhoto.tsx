"use client";
import { useEffect, useRef, useState } from "react";
import { useImage } from "@/lib/store/images";
import { useGarmentImage } from "@/lib/garmentImage";
import { productPrompt } from "@/lib/stylist";
import { cx } from "@/lib/util";
import type { Category } from "@/lib/types";

export interface PhotoSubject {
  name: string;
  category?: Category;
  color?: string;
  colorHex?: string;
  fabric?: string;
  neckline?: string;
  fit?: string;
  silhouette?: string;
  length?: string;
  detail?: string;
  imageId?: string;
  imageUrl?: string;
}

/** Generate only once the image is (nearly) on screen — saves cost and rate limit. */
function useInView<T extends Element>() {
  const ref = useRef<T>(null);
  const [seen, setSeen] = useState(false);
  useEffect(() => {
    if (!ref.current || seen) return;
    const io = new IntersectionObserver(([e]) => e.isIntersecting && setSeen(true), { rootMargin: "200px" });
    io.observe(ref.current);
    return () => io.disconnect();
  }, [seen]);
  return [ref, seen] as const;
}

/**
 * A garment shown as a photograph: the user's own photo if they uploaded one, otherwise a
 * photorealistic product photo generated by MY GALA's server (Replicate).
 */
export default function GarmentPhoto({ g, className, prompt: promptOverride, regenerable = true }: { g: PhotoSubject; className?: string; label?: boolean; prompt?: string; regenerable?: boolean }) {
  const own = useImage(g.imageId);
  const prompt = own || g.imageUrl ? undefined : promptOverride ?? productPrompt({ ...g, shadeHex: undefined });
  const [ref, seen] = useInView<HTMLDivElement>();
  const gen = useGarmentImage(prompt, seen);
  const src = own ?? g.imageUrl ?? gen.src;
  return (
    <div ref={ref} className={cx("gphoto", className, gen.loading && "loading", gen.error && "failed")}>
      {src && <img key={src.slice(0, 64) + src.length} src={src} alt={g.name} referrerPolicy="no-referrer" />}
      {!src && gen.error && (
        <div className="gphoto-fail"><span className="gf-name">{g.name}</span><span>{gen.error}</span></div>
      )}
      {src && prompt && regenerable && (
        <button type="button" className="gphoto-new" title="Generate a new photo" onClick={(e) => { e.stopPropagation(); gen.regenerate(); }}>New photo</button>
      )}
    </div>
  );
}
